//🔥 Tipos de colecciones (.NET)


/* 1. 📋 List
✔️ ordenada
✔️ permite repetidos
✔️ acceso por índice */

List<int> numeros = new List<int>();

/* 2. 🧺 HashSet
✔️ no permite repetidos
✔️ no garantiza orden */

HashSet<int> numeros = new HashSet<int>();

/* 3. 🗝️ Dictionary
✔️ clave → valor
✔️ búsqueda rápida por clave */

Dictionary<int, string> alumnos = new Dictionary<int, string>();